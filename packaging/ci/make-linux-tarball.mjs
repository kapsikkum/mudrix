#!/usr/bin/env node
// Makes the tarball the Arch, Fedora and Nix jobs install, from the deb bundle of the CI Linux build,
// plus the filled PKGBUILD and RPM spec for that local tarball. apps/desktop/scripts/package-linux.mjs
// does the same for a signed release; this one does not sign and needs no rpm bundle.
//
//   node packaging/ci/make-linux-tarball.mjs
//
// Writes target/debug/bundle/tarball/{mudrix-<version>-linux-x86_64.tar.gz,PKGBUILD,mudrix.spec}.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';

const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
// The CI passes the profile directory it built (target/debug or target/release); a local run defaults to debug.
const bundle = process.env.MUDRIX_BUNDLE_DIR ?? 'target/debug/bundle';

const deb = join(bundle, 'deb');
const debDir =
  existsSync(deb) && readdirSync(deb).find((name) => existsSync(join(deb, name, 'data')));
if (!debDir)
  throw new Error(`no deb bundle in ${deb}: build the deb bundle for this profile first`);

const out = join(bundle, 'tarball');
const stage = join(out, 'stage');
rmSync(out, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
cpSync(join(deb, debDir, 'data'), stage, { recursive: true });
cpSync('LICENSE', join(stage, 'LICENSE'));

// Tauri marks the binary in each package with the kind of package it came from; the tarball's copy must
// not claim to be a deb, or the updater would try to upgrade through dpkg. The binary is scanned as a
// Buffer: a debug build is over Node's 512 MiB string limit, so reading it as text throws.
const marker = Buffer.from('__TAURI_BUNDLE_TYPE_VAR_');
const kinds = new Set(['DEB', 'RPM', 'APP']);
const bin = join(stage, 'usr/bin');
for (const name of readdirSync(bin)) {
  const file = join(bin, name);
  const buf = readFileSync(file);
  let at = 0;
  let changed = false;
  for (;;) {
    at = buf.indexOf(marker, at);
    if (at === -1) break;
    const kindAt = at + marker.length;
    const kind = buf.toString('latin1', kindAt, kindAt + 3);
    if (kinds.has(kind)) {
      buf.write('UNK', kindAt, 'latin1');
      changed = true;
    }
    at = kindAt + 3;
  }
  if (changed) writeFileSync(file, buf);
}

const tarball = `mudrix-${version}-linux-x86_64.tar.gz`;
execFileSync('tar', ['-czf', join(out, tarball), '-C', stage, 'usr', 'LICENSE']);
rmSync(stage, { recursive: true, force: true });
const sha256 = createHash('sha256')
  .update(readFileSync(join(out, tarball)))
  .digest('hex');

// Arch: the AUR PKGBUILD points at the GitHub release; this copy takes the tarball next to it instead,
// with a real checksum, which is what `makepkg --nodeps` builds in CI. Line endings are normalised:
// bash would read a CRLF PKGBUILD as part of every value.
const pkgbuild = readFileSync('packaging/aur/mudrix-bin/PKGBUILD', 'utf8')
  .replaceAll('\r\n', '\n')
  .replace(
    /^#.*\n/,
    '# Generated by packaging/ci/make-linux-tarball.mjs: a local tarball, not a release\n'
  )
  .replace(/^_version=.*$/m, `_version=${version}`)
  .replace(/^pkgver=.*$/m, `pkgver=${version.replaceAll('-', '_')}`)
  .replace(/^source=.*$/m, `source=("${tarball}")`)
  .replace(/^sha256sums=.*$/m, `sha256sums=('${sha256}')`);
writeFileSync(join(out, 'PKGBUILD'), pkgbuild);

// Fedora: RPM versions cannot contain '-' (26.12.1-next.1 is version 26.12.1, release 0.next.1), the
// same split Tauri uses for its rpm bundle. The source is the same local tarball.
const [rpmVersion, ...pre] = version.split('-');
const rpmRelease = pre.length > 0 ? `0.${pre.join('-').replaceAll('-', '_')}` : '1';
const spec = readFileSync('packaging/fedora/mudrix.spec', 'utf8')
  .replaceAll('\r\n', '\n')
  .replace(/^Version:.*$/m, `Version:        ${rpmVersion}`)
  .replace(/^Release:.*$/m, `Release:        ${rpmRelease}%{?dist}`)
  .replace(/^Source0:.*$/m, `Source0:        ${tarball}`);
writeFileSync(join(out, 'mudrix.spec'), spec);

console.log(`wrote ${join(out, tarball)} (sha256 ${sha256}), PKGBUILD and mudrix.spec`);
